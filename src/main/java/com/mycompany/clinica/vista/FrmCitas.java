    /** Cambia el estado de la cita seleccionada en la tabla (confirmar o cancelar) y refresca la lista. */
    private void cambiarEstadoDeLaCitaSeleccionada(EstadoCita nuevoEstado, String mensajeExito, String mensajeError) {
        if (!Permisos.puedeGestionarCitas()) {
            JOptionPane.showMessageDialog(this, "No tiene permiso para realizar esta acción.",
                    "Acceso denegado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int filaSeleccionada = jTable1.getSelectedRow();
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Por favor, seleccione una cita de la tabla.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idCita = (int) jTable1.getValueAt(filaSeleccionada, 0);

        try {
            if (citaService.actualizarEstado(idCita, nuevoEstado)) {
                JOptionPane.showMessageDialog(this, mensajeExito, "Éxito", JOptionPane.INFORMATION_MESSAGE);
                listarCitasEnTabla();
            } else {
                JOptionPane.showMessageDialog(this, mensajeError, "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException e) {
            logger.log(java.util.logging.Level.SEVERE, "Error al cambiar el estado de la cita", e);
            JOptionPane.showMessageDialog(this, "Error de base de datos:\n" + e.getMessage(),
                    "Error SQL", JOptionPane.ERROR_MESSAGE);
        } catch (ReglaNegocioException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Advertencia", JOptionPane.WARNING_MESSAGE);
            listarCitasEnTabla(); // la tabla pudo quedar desactualizada
        }
    }

    /** Estilo de la tabla de citas (se aplica una sola vez, al abrir la ventana). */
    private void estilizarTabla() {
        jTable1.setFont(new java.awt.Font("Segoe UI", java.awt.Font.PLAIN, 13));
        jTable1.setForeground(new java.awt.Color(51, 65, 85)); // Color slate oscuro
        jTable1.setRowHeight(32); // Da una altura espaciosa y elegante a las filas
        jTable1.setShowVerticalLines(false); // Estilo web moderno: sin líneas verticales
        jTable1.setGridColor(new java.awt.Color(226, 232, 240)); // Líneas horizontales gris muy claro

        // Personalizar el Encabezado (mismo azul oscuro/slate que usa el grupo)
        javax.swing.table.JTableHeader encabezado = jTable1.getTableHeader();
        encabezado.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 13));
        encabezado.setBackground(new java.awt.Color(15, 23, 42)); // Color oscuro corporativo
        encabezado.setForeground(java.awt.Color.WHITE); // Texto del título en blanco
        encabezado.setPreferredSize(new java.awt.Dimension(0, 36)); // Encabezado más alto y estilizado

        // Hacer la tabla responsiva (se estira sola al cambiar el tamaño de la ventana)
        jTable1.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_ALL_COLUMNS);

        // Suavizar los bordes del scroll del componente contenedor
        jScrollPane1.setBorder(javax.swing.BorderFactory.createLineBorder(new java.awt.Color(226, 232, 240), 1));
    }

    /** Carga en la tabla todas las citas guardadas en la base de datos. */
    public void listarCitasEnTabla() {
        ModeloTabla modelo = new ModeloTabla("ID", "Fecha", "Hora", "Motivo", "Estado", "ID Paciente", "ID Médico");

        try {
            for (Cita cita : citaService.obtenerTodasLasCitas()) {
                modelo.addRow(new Object[]{
                        cita.getIdCita(),
                        cita.getFechaCita(),
                        cita.getHoraCita(),
                        cita.getMotivo(),
                        cita.getEstado(),
                        cita.getIdPaciente(),
                        cita.getIdMedico()
                });
            }
        } catch (SQLException e) {
            logger.log(java.util.logging.Level.SEVERE, "Error al cargar la tabla de citas", e);
            JOptionPane.showMessageDialog(this, "No se pudieron cargar las citas:\n" + e.getMessage(),
                    "Error SQL", JOptionPane.ERROR_MESSAGE);
        }

        jTable1.setModel(modelo);
    }

